"""День 14: Streamlit-чат агентов DeepSeek с памятью, задачей и инвариантами.

Приложение общается с FastAPI-бэкендом (порт 8000) по HTTP через `requests`.
Ключ DEEPSEEK_API_KEY фронтенду НЕ нужен — его читает бэкенд (day14/.env или
переменная окружения). Все данные хранит бэкенд в SQLite (day14/agents.db),
поэтому они переживают рестарт.

Что нового по сравнению с днём 13: **инварианты** — правила проекта, которые
агент не имеет права нарушать. Они лежат в отдельной таблице `invariants` (не в
истории сообщений), подставляются блоком в системный промпт каждого запроса, а
предложение проверяется перед выдачей: сначала детерминированными правилами, при
неоднозначности — вызовом LLM. Нарушение hard-инварианта превращается в отказ
(с объяснением, какое правило нарушено), нарушение soft — в предупреждение, но
решение предлагается.

Интерфейс — четыре раздела основной области (переключатель вверху страницы):

- «💬 Чат и память» — диалог вручную, панели трёх слоёв памяти (краткосрочная,
  рабочая, долговременная), индикатор того, что ушло в последний запрос,
  сравнение режимов сжатия; предупреждение или отказ по инвариантам последнего
  хода показывается прямо над полем ввода; стратегия, задача и сессия — в
  боковой панели;
- «👤 Профиль пользователя» — выбор профиля, форма редактирования, готовые
  профили для демонстрации, быстрое переключение профиля активного агента и
  сравнение двух профилей на одном вопросе;
- «🧭 Состояние задачи» — текущий этап и шаг, ожидаемое действие, схема
  переходов, пять кнопок (пауза, продолжение, следующий шаг, откат, завершение)
  и журнал переходов;
- «📏 Инварианты» — список правил проекта с фильтрами, форма создания, правка,
  включение-выключение и удаление, а также проверка произвольного текста тем же
  способом, которым агент проверяет свой ход.

Запуск из папки day14/:  streamlit run app.py  (бэкенд запускается отдельно:
uvicorn backend.api.main:app --port 8000)

Код интерфейса разложен по пакету ``frontend/``: ``api_client`` (HTTP-транспорт),
``common`` (подписи, форматтеры, состояние), ``sidebar``, ``chat_section``,
``context_panels``, ``memory_panels``, ``profile_section``,
``profile_comparison``, ``task_panel``, ``invariant_panel``.
"""
