"""День 21: Streamlit-чат агентов DeepSeek с индексацией документов.

Приложение общается с FastAPI-бэкендом (порт 8000) по HTTP через `requests`.
Ключ DEEPSEEK_API_KEY фронтенду НЕ нужен — его читает бэкенд (day21/.env или
переменная окружения). Все данные хранит бэкенд в SQLite (day21/agents.db),
поэтому они переживают рестарт.

Что нового по сравнению с днём 19: **оркестрация нескольких MCP-серверов**.
Вместо одного сервера дня работают три независимых процесса по stdio
(`mcp_servers/search_server`, `data_server`, `storage_server`), их конфигурация
лежит данными в `mcp_servers.json`, а реестр дня держит по соединению на сервер и
маршрутизирует вызов по имени инструмента. Оркестратор строит план шагов (план
может предложить LLM: «определи, какие инструменты с каких серверов нужно вызвать
и в каком порядке»), сам подключает нужный сервер и логирует каждый шаг в таблицу
`orchestration_steps` (плюс запуск — в `orchestration_runs`). Реплика «найди данные
про RAG и сохрани в базу» проходит цепочкой search_server → data_server →
storage_server, а результат уходит в системный промпт того же запроса.

День 19 добавил декларативный пайплайн, день 18 — планировщик, день 17 — MCP-клиент
и свой сервер, день 15 — контролируемые переходы, день 14 — инварианты.

Интерфейс — девятнадцать разделов основной области (переключатель вверху страницы):

- «💬 Чат и память» — диалог вручную, панели трёх слоёв памяти, индикатор того,
  что ушло в последний запрос, сравнение режимов сжатия, уведомления планировщика;
- «👤 Профиль пользователя» — выбор профиля, форма редактирования, готовые
  профили для демонстрации, сравнение двух профилей на одном вопросе;
- «🧭 Состояние задачи» — этап и шаг, ожидаемое действие, граф допуска,
  доступные и недоступные переходы с причинами, флаги-согласования и журнал;
- «📏 Инварианты» — правила проекта с фильтрами, форма создания, правка,
  включение-выключение и удаление, проверка произвольного текста;
- «🔌 MCP» — цель подключения, транспорт, статус, каталог серверов флота,
  таблица инструментов, ручной вызов и блок «🤖 Спросить агента»;
- «🗓 Планировщик» — состояние планировщика, таблица задач с действиями, форма
  создания задачи по аргументам инструмента, напоминания, сводки с метриками и
  текстом, история запусков задачи;
- «🔀 Пайплайны» — подключение к серверу дня, запуск пайплайна, прогресс по шагам,
  схема потока данных с объёмами, история запусков с деталями шагов и удалением;
- «🌐 Оркестрация» — три MCP-сервера с их инструментами и обновлением кэша, кнопка
  «🚀 Запустить демо-сценарий» (пять шагов по трём серверам с живым прогрессом),
  диаграмма флоу, таблица шагов с входными и выходными данными, история запусков и
  статистика вызовов по серверам;
- «💰 Расходы» — пик или непик сейчас и прогноз экономии, доля ввода из кэша
  контекста, статистика стабильных префиксов промпта и сжатия, график расхода по
  дням, журнал последних запросов с cache_hit/cache_miss и таблица «тип задачи →
  модель»;
- «📦 Индексация» — кнопка «🚀 Запустить демо-индексацию» (документы → чанки двух
  стратегий → эмбеддинги → FAISS + SQLite → поиск → сравнение с живым прогрессом),
  таблица метрик и гистограммы размеров чанков, примеры чанков, форма ручного
  поиска по индексу и история запусков;
- «🆚 RAG-сравнение» — один вопрос на двух дорожках: ответ без корпуса рядом с
  ответом по корпусу, источники и метрики контекста у каждого;
- «🧪 RAG-демо» — десять контрольных вопросов одной кнопкой: режим, ответ,
  источники, цитаты и вердикт по каждому, включая режим «не знаю»;
- «🏠 Локальный RAG» — сравнение локальной и облачной модели на десяти вопросах
  одной кнопкой: ответы обеих сторон, источники, время, режим и вердикт по строке;
- «⚙️ Оптимизация локальной LLM» — профили настройки (`baseline`/`tuned`) и теги
  моделей (кванты) на тех же десяти вопросах: вердикты, цитаты, опора, время,
  токенов в секунду, занятая VRAM и вердикт «до/после» по каждой модели;
- «🖥 Локальная LLM» — второй провайдер ответа (Ollama по HTTP): вопросы дня 26
  одной кнопкой, ответы, время, токены в секунду и оценка качества;
- «🛰 Удалённая LLM» — та же модель в Google Colab через туннель Cloudflare:
  адрес и ручки раздела, проверка связи и демо из пяти шагов одной кнопкой;
- «🧑‍💻 Ассистент разработчика (Day 31)» — `/help <вопрос>`: ответ по документации
  проекта (RAG) и состоянию репозитория (MCP dev_server), источники и список
  MCP-инструментов в раскрывающихся блоках, текущая ветка и переключатель провайдера;
- «🔎 AI-ревью кода (Day 32)» — ревью PR: diff локальный или из GitHub, контекст
  корпуса, находки по рискам P0–P3 и публикация комментария в PR;
- «🎧 Поддержка пользователей (Day 33)» — вопрос клиента: документация поддержки из
  корпуса плюс профиль и тикет из MCP, селекторы клиента/тикета и карточка контекста.

Запуск из папки day21/:  streamlit run app.py  (бэкенд запускается отдельно:
uvicorn backend.api.main:app --port 8000)

Код интерфейса разложен по пакету ``frontend/``: ``api_client`` (HTTP-транспорт), ``common``
(подписи, форматтеры, состояние), ``sidebar``, ``chat_section`` (разделы целиком),
``context_panels`` и ``memory_panels`` (панели стратегии и слоёв памяти), ``profile_section``
и ``profile_comparison``, ``task_panel`` и ``task_transitions``, ``invariant_panel``,
``mcp_api``/``mcp_section``/``mcp_call``/``mcp_ask`` (раздел «🔌 MCP»), ``scheduler_api`` и
``scheduler_section`` (раздел «🗓 Планировщик»), ``notifications`` (уведомления фоновых
задач), ``pipeline_api`` и ``pipeline_section`` (раздел «🔀 Пайплайны»), ``orchestration_api``
и ``orchestration_section`` (раздел «🌐 Оркестрация»), ``indexing_api``, ``indexing_section``,
``indexing_compare`` и ``indexing_search`` (раздел «📦 Индексация»), ``cost_api`` и
``cost_section`` (вкладка «💰 Расходы»), ``rag_api``, ``rag_section`` и ``rag_demo_section``
(разделы RAG), ``llm_api`` и ``local_llm_section`` («🖥 Локальная LLM»), ``local_rag_section``,
``local_tuning_section``, ``remote_llm_api`` и ``remote_llm_section`` («🛰 Удалённая LLM»),
``dev_assistant_api`` и ``dev_assistant_section`` («🧑‍💻 Ассистент разработчика»),
``code_review_api`` и ``code_review_section`` («🔎 AI-ревью кода»), ``support_api`` и
``support_section`` («🎧 Поддержка пользователей»).
"""
