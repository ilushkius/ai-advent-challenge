"""Пакет frontend дня 19 (Streamlit): модули интерфейса, разложенные по доменам.

Модули:

- ``api_client`` — HTTP-транспорт к бэкенду (единственное место, знающее про HTTP);
- ``common`` — подписи, форматтеры и состояние страницы (``st.session_state``);
- ``sidebar`` — боковая панель: агенты, сессия, стратегия, задача;
- ``chat_section`` — раздел «💬 Чат и память»: карточка агента, панели, диалог, ввод;
- ``main_sections`` — переключатель разделов основной области и цепочка их отрисовки
  (день 34: вынесен из ``chat_section``, который стоит на пределе 400 строк);
- ``context_panels`` / ``memory_panels`` — панели контекста и трёх слоёв памяти;
- ``profile_section`` / ``profile_comparison`` — раздел «👤 Профиль пользователя»;
- ``task_panel`` — раздел «🧭 Состояние задачи»;
- ``task_transitions`` — блок переходов по этапам, паузы и флагов-согласований;
- ``invariant_panel`` — раздел «📏 Инварианты»: правила проекта и проверка текста;
- ``mcp_section`` — раздел «🔌 MCP»: подключение к MCP-серверу, каталог серверов,
  статус, список инструментов и вызов;
- ``mcp_api`` — HTTP-запросы MCP-раздела (``/mcp/...``) поверх ``api_client``;
- ``mcp_call`` — ручной вызов инструмента (форма по ``input_schema``) и каталог
  известных серверов;
- ``mcp_ask`` — блок «🤖 Спросить агента»: агент вызывает инструмент сам;
- ``scheduler_api`` — HTTP-запросы планировщика (``/scheduler/...``, день 18)
  поверх ``api_client``;
- ``scheduler_section`` — раздел «🗓 Планировщик»: задачи, напоминания, сводки,
  история запусков и форма создания задачи (день 18);
- ``notifications`` — непрочитанные уведомления планировщика в основной области
  чата: фрагмент с автообновлением (день 18);
- ``pipeline_api`` — HTTP-запросы пайплайна (``/pipelines/...``, день 19) поверх
  ``api_client``;
- ``pipeline_section`` — раздел «🔀 Пайплайны»: подключение MCP, форма запуска,
  прогресс по шагам (фрагмент раз в секунду), схема потока данных и история
  запусков (день 19);
- ``indexing_api`` — HTTP-запросы индексации (``/indexing/...``, день 21) поверх
  ``api_client``;
- ``indexing_section`` — раздел «📦 Индексация»: кнопка демо-прогона, прогресс
  этапов (фрагмент раз в секунду), сравнение стратегий и история запусков (день 21);
- ``indexing_compare`` — таблица метрик, гистограммы размеров чанков, примеры
  чанков и результаты пяти тестовых запросов (день 21);
- ``indexing_search`` — форма ручного поиска по построенному индексу (день 21);
- ``cost_api`` — HTTP-запросы расходов (``/llm/...``, день 21) поверх ``api_client``;
- ``cost_section`` — вкладка «💰 Расходы»: непиковые часы, кэш контекста, сжатие,
  график расхода по дням, журнал запросов и маршрутизация моделей (день 21);
- ``support_api`` — HTTP-запросы ассистента поддержки (``/support/...``, день 33)
  поверх ``api_client``;
- ``support_section`` — раздел «🎧 Поддержка пользователей»: селекторы клиента и
  тикета из MCP, карточка контекста, диалог с источниками и контекстом (день 33);
- ``file_assistant_api`` — HTTP-запросы ассистента файлов (``/file-assistant/...``,
  день 34) поверх ``api_client``;
- ``file_assistant_section`` — раздел «🗂 Ассистент файлов»: цель, режим ``dry_run``,
  провайдер, план, выполненные шаги, файлы, diff и история запусков (день 34).

Модули не выполняют ``st.*`` на импорте — только определения и константы;
страницу собирает ``app.py``: ``set_page_config`` → ``common.init_state()`` →
``sidebar.render_sidebar()`` → ``chat_section.render_main_area()``.
"""
