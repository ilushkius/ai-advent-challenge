"""HTTP-часть фронтенда дня 26 для провайдера ответа и локальной модели.

Транспорт общий — ``frontend/api_client.py`` (``request_json``, ``BackendError``);
здесь только два запроса: состояние провайдера (кто выбран по умолчанию, какая
модель и адрес стоят локально) и демо локальной модели — три запроса к Ollama,
которые бэкенд делает по HTTP и возвращает вместе со временем и токенами.

Отдельный модуль, как ``cost_api.py`` и ``rag_api.py``: ``api_client`` держит
транспорт и домены дня 21, туда его 400 строк не пускают.
"""
from .api_client import LONG_TIMEOUT, request_json


def api_llm_provider() -> dict:
    """GET /llm/provider -> провайдер по умолчанию, подписи, модель, адрес, таймаут."""
    return request_json("GET", "/llm/provider")


def api_local_demo() -> dict:
    """POST /llm/local-demo -> три запроса к Ollama: ответы, время, токены, качество.

    Тело не отправляется намеренно: демо всегда локальное — платить токенами
    облака за проверку второго провайдера нечем оправдать. Таймаут длинный:
    первый запрос грузит веса модели в память (десятки секунд).
    """
    return request_json("POST", "/llm/local-demo", timeout=LONG_TIMEOUT)
