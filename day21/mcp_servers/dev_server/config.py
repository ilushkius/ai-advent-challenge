"""Константы MCP-сервера разработки (день 31): корни, границы аргументов, тексты.

Модуль без зависимости от SDK: его импортируют ``tools.py``, ``server.py`` и тесты.
Два корня, потому что у инструментов разные области:

- ``REPO_ROOT`` (корень репозитория ``ai-challenge/``) — область инструментов git:
  ветка и коммит относятся к репозиторию целиком, а не к папке дня;
- ``DAY_ROOT`` (``day21/``) — область ``get_project_structure``: дерево проекта,
  который разрабатывают, начинается с папки дня, иначе ответ тонул бы в архиве
  дней 1–20 и правилах репозитория.

Приём с путями тот же, что в ``search_server/config.py``: сервер запускается
ОТДЕЛЬНЫМ процессом, где ни корень дня, ни корень репозитория в ``sys.path`` не
попадают (``REPO_ROOT`` добавляется ради общего пакета ``shared/``).
"""
import sys
from pathlib import Path

#: Корень дня (day21/mcp_servers/dev_server/config.py → day21/) и корень репозитория.
DAY_ROOT = Path(__file__).resolve().parents[2]
REPO_ROOT = DAY_ROOT.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

#: Имя и версия сервера: уходят клиенту в ответе ``initialize``.
SERVER_NAME = "day21-dev"
SERVER_VERSION = "1.0.0"

#: Инструкция сервера: клиент показывает её модели рядом с каталогом инструментов.
SERVER_INSTRUCTIONS = (
    "Четыре инструмента контекста разработки. get_git_branch без аргументов "
    "возвращает ветку, последний коммит, список изменённых файлов и признак "
    "чистого дерева. list_files(directory=\"day21/backend\", extension=\".py\") "
    "перечисляет файлы каталога (нерекурсивно, путь от корня репозитория, "
    "extension без ведущей точки тоже принимается). get_git_diff(lines=50) "
    "возвращает последние строки diff рабочего дерева и индекса относительно "
    "HEAD. get_project_structure(max_depth=3) отдаёт дерево папки day21/ с "
    "числом каталогов и файлов."
)

#: Сколько файлов возвращает ``list_files``: каталог целиком читается глазами модели.
MAX_FILES = 200
#: Сколько изменённых файлов возвращает ``get_git_branch``.
MAX_MODIFIED = 50
#: Сколько имён файлов показывается на каталог в дереве ``get_project_structure``.
MAX_TREE_FILES = 20
#: Границы глубины дерева: нулевая глубина не показала бы ничего, пяти хватает на
#: самое глубокое место папки дня (``backend/services/``, ``tests/integration/``).
MIN_DEPTH, MAX_DEPTH = 1, 5
#: Границы аргумента ``lines`` у ``get_git_diff``: одна строка бессмысленна, 500 —
#: предел читаемости в контексте модели.
MIN_DIFF_LINES, MAX_DIFF_LINES = 1, 500
#: Таймаут одного вызова git, секунды: ``git status`` на большом дереве медленный,
#: но подвисший процесс хуже медленного ответа.
GIT_TIMEOUT = 15.0
#: Каталоги, которые не показываются в дереве: служебные и слишком объёмные
#: (``models`` — веса локальных моделей, сотни мегабайт).
SKIP_DIRS = frozenset({"__pycache__", ".git", ".pytest_cache", ".venv",
                       ".mypy_cache", ".ruff_cache", "models"})
