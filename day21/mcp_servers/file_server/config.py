"""Константы MCP-сервера файлов (день 34): корни, границы аргументов, тексты.

Модуль без зависимости от SDK: его импортируют ``tools.py``, ``server.py`` и тесты.
Корень дня нужен, потому что сервер запускается ОТДЕЛЬНЫМ процессом, где ни корень
дня, ни корень репозитория в ``sys.path`` не попадают: без него импорт
``mcp_servers.file_server.*`` и вызов ``shared.logging_utils`` не разрешились бы
(``REPO_ROOT`` добавляется ради общего пакета ``shared/``).

Два корня, потому что у инструментов разные области:

- ``DAY_ROOT`` (``day21/``) — рабочая область самих инструментов: пути аргументов
  относительны ей, и выйти за неё нельзя (``_resolve`` в ``tools.py``);
- ``REPO_ROOT`` (``ai-challenge/``) — область инструмента git: ``get_file_diff``
  сравнивает файл с ``HEAD`` того репозитория, в котором он лежит, а файл вне
  репозитория честно отвечает текстом ``NOT_TRACKED_NOTE``.

Границы аргументов объявлены здесь, а проверяются в ``tools.py``: схема инструмента
описывает ТИПЫ (SDK собирает её из аннотаций), а «не больше 200 совпадений» или
«режим записи только ``overwrite`` или ``append``» — правила предметной области,
и каждое нарушение бросает ``ToolError`` с русским текстом.
"""
import sys
from pathlib import Path

#: Корень дня (day21/mcp_servers/file_server/config.py → day21/) и корень репозитория.
DAY_ROOT = Path(__file__).resolve().parents[2]
REPO_ROOT = DAY_ROOT.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

#: Имя и версия сервера: уходят клиенту в ответе ``initialize``.
SERVER_NAME = "day21-files"
SERVER_VERSION = "1.0.0"

#: Инструкция сервера: клиент показывает её модели рядом с каталогом инструментов.
SERVER_INSTRUCTIONS = (
    "Шесть инструментов работы с файлами проекта (пути относительны корню day21/). "
    "list_files(directory=\".\", extension=\"py\") перечисляет имена файлов каталога "
    "без рекурсии. search_in_files(pattern=\"IndexService\", directory=\".\", "
    "file_glob=\"*.py\") ищет регулярное выражение по файлам рекурсивно и отдаёт "
    "путь, номер строки, найденный текст, саму строку и контекст до и после "
    "(не больше 500 файлов и 200 совпадений). read_file(path=\"backend/api/main.py\", "
    "max_bytes=100000) возвращает содержимое файла, размер, число символов и строк "
    "и признак обрезки. write_file(path=\"docs/adr/0001.md\", content=\"…\", "
    "mode=\"overwrite\") создаёт каталоги и записывает файл (mode: overwrite или "
    "append). apply_patch(path=\"docs/usage.md\", old_text=\"…\", new_text=\"…\") "
    "заменяет ПЕРВОЕ вхождение old_text и сообщает, сколько вхождений нашлось всего. "
    "get_file_diff(path=\"docs/usage.md\") отдаёт unified diff файла относительно "
    "HEAD. Путь вне корня day21/ и несуществующий файл приходят ошибкой инструмента."
)

#: Кодировка чтения и записи: файлы дня — UTF-8, битые байты читаются заменой.
ENCODING = "utf-8"

#: Пределы аргументов инструментов.
MAX_BYTES = 1_000_000                 # верхняя граница max_bytes у read_file
DEFAULT_MAX_BYTES = 100_000           # значение по умолчанию
MAX_SEARCH_FILES = 500                # сколько файлов просматривает search_in_files
MAX_SEARCH_MATCHES = 200              # сколько совпадений возвращает search_in_files
CONTEXT_LINES = 3                     # строк контекста до и после совпадения
MAX_FILES = 200                       # сколько имён возвращает list_files
MAX_WRITE_CHARS = 200_000             # предел content у write_file
MODES = ("overwrite", "append")       # режимы write_file

#: Служебные каталоги, которые не просматривает поиск: рантайм, кэши и данные
#: (``models`` — веса локальных моделей, ``index``/``documents`` — артефакты
#: индексации: их содержимое не текст проекта, а тысячи строк из чужих файлов).
SKIP_DIRS = frozenset({"__pycache__", ".git", ".pytest_cache", ".venv",
                       ".mypy_cache", ".ruff_cache", "models", "index", "documents"})

#: Таймаут одного вызова git, секунды: подвисший процесс хуже медленного ответа.
GIT_TIMEOUT = 15.0

#: Ответ ``get_file_diff`` для файла вне репозитория git (временный корень теста).
NOT_TRACKED_NOTE = "Файл вне репозитория git: {path}"
#: Ответ ``get_file_diff``, когда рабочее дерево совпадает с HEAD по этому файлу.
NO_CHANGES = "Изменений относительно HEAD нет."
