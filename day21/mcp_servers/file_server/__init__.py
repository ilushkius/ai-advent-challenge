"""MCP-сервер файлов (день 34): ``list_files``, ``search_in_files``, ``read_file``, ``write_file``, ``apply_patch``, ``get_file_diff``.

Отдельный процесс по stdio: его поднимает СВОИМ клиентом служба ассистента файлов
(``backend/services/file_assistant_service``), а не флот дня 20 из
``mcp_servers.json`` — сервер вне флота, и файл ``mcp_servers.json`` из-за него не
меняется: у флота свои три сервера, и раздел «🌐 Оркестрация» от этого пакета не
зависит. Инструменты отвечают про ФАЙЛЫ папки дня: что лежит в каталоге, где
встречается образец, что в файле написано, и как изменить файл — создать, дописать,
заменить фрагмент. Diff файла относительно ``HEAD`` закрывает цикл: ассистент сам
инициирует работу с файлами, а пользователь видит результат глазами.

Слои пакета:

- ``config.py`` — корни путей (``DAY_ROOT`` для инструментов, ``REPO_ROOT`` для
  git), имя и инструкция сервера, границы аргументов;
- ``schemas.py`` — структуры ответов инструментов (``TypedDict`` → ``outputSchema``):
  содержимое файла, результат записи и результат замены;
- ``tools.py`` — тела шести инструментов (разрешение путей по корню, поиск, запись,
  замена);
- ``diffing.py`` — diff файла: ``git diff HEAD`` для отслеживаемых и синтез для
  только что созданных (``git`` их ещё не знает);
- ``server.py`` — сборка ``MCPServer``, аргумент ``--file-root`` и точка входа.

Запуск руками (сервер ждёт JSON-RPC на stdin — это транспорт протокола, а не
зависание; обычно его поднимает клиент ассистента файлов):

    uv run python mcp_servers/file_server/server.py
    uv run python mcp_servers/file_server/server.py --file-root .
"""
