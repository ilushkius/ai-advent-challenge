"""День 15: Streamlit-чат агентов DeepSeek с задачей, инвариантами и переходами.

Приложение общается с FastAPI-бэкендом (порт 8000) по HTTP через `requests`.
Ключ DEEPSEEK_API_KEY фронтенду НЕ нужен — его читает бэкенд (day15/.env или
переменная окружения). Все данные хранит бэкенд в SQLite (day15/agents.db),
поэтому они переживают рестарт.

Что нового по сравнению с днём 14: **контролируемые переходы** состояния задачи.
Задача ходит по этапам только по объявленному графу: переход вперёд открыт после
согласования этапа (флаги «план утверждён», «реализация завершена», «валидация
пройдена»), а недопустимая попытка — в интерфейсе, в API или в ответе агента —
отклоняется с объяснением и остаётся в журнале попыток. В разделе «Состояние
задачи» видны доступные и недоступные переходы: кнопки этапов гасятся, а причина
отказа показывается и в подсказке, и списком.

День 14 добавил **инварианты** — правила проекта, которые агент не имеет права
нарушать. Они лежат в отдельной таблице `invariants` (не в истории сообщений),
подставляются блоком в системный промпт каждого запроса, а предложение
проверяется перед выдачей: сначала детерминированными правилами, при
неоднозначности — вызовом LLM. Нарушение hard-инварианта превращается в отказ
(с объяснением, какое правило нарушено), нарушение soft — в предупреждение, но
решение предлагается.

Интерфейс — четыре раздела основной области (переключатель вверху страницы):

- «💬 Чат и память» — диалог вручную, панели трёх слоёв памяти (краткосрочная,
  рабочая, долговременная), индикатор того, что ушло в последний запрос,
  сравнение режимов сжатия; предупреждение или отказ по инвариантам последнего
  хода показывается прямо над полем ввода; стратегия, задача и сессия — в
  боковой панели;
- «👤 Профиль пользователя» — выбор профиля, форма редактирования, готовые
  профили для демонстрации, быстрое переключение профиля активного агента и
  сравнение двух профилей на одном вопросе;
- «🧭 Состояние задачи» — текущий этап и шаг, ожидаемое действие, граф допуска,
  доступные и недоступные переходы с причинами, флаги-согласования и журнал в
  двух разрезах: состоявшиеся переходы и отклонённые попытки;
- «📏 Инварианты» — список правил проекта с фильтрами, форма создания, правка,
  включение-выключение и удаление, а также проверка произвольного текста тем же
  способом, которым агент проверяет свой ход.

Запуск из папки day15/:  streamlit run app.py  (бэкенд запускается отдельно:
uvicorn backend.api.main:app --port 8000)

Код интерфейса разложен по пакету ``frontend/``: ``api_client`` (HTTP-транспорт),
``common`` (подписи, форматтеры, состояние), ``sidebar``, ``chat_section``,
``context_panels``, ``memory_panels``, ``profile_section``,
``profile_comparison``, ``task_panel``, ``task_transitions``, ``invariant_panel``.
"""
