"""Распознавание предложения модели перейти в другой этап задачи (день 15).

Что это.
    Чистая эвристика «по ответу»: по фразам в тексте ответа модели
    определяется, о переходе в какой этап она говорит («задача завершена» →
    ``done``, «перехожу к тестам» → ``validation``). Результат —
    ``TaskStage`` или ``None``; сам ответ ничего в БД не пишет, а решение
    «можно ли туда» принимает домен
    (``backend/domain/task_state_machine.py``): недопустимый переход агент
    заменяет отказом с объяснением.

Почему таблица фраз, а не структурированный протокол ответа.
    Приём уже принят в проекте для реплик пользователя
    (``backend/domain/task_intent.py``): фразы, границы слов, приоритет групп.
    Он не требует менять контракт ответа модели и работает с обычным текстом,
    а цена ошибки невелика — предложение лишь проверяется, а не выполняется.

Как запустить.
    Модуль чистый: только ``enum``-члены ``task_fsm.py`` и ``re``, никаких БД,
    сети и UI. Побочных эффектов на импорте нет. Проверяется тестами:

        # из папки day16
        uv run pytest -q tests/unit/test_task_proposal.py
"""

from __future__ import annotations

import re
from typing import Optional

from .task_fsm import STAGE_ORDER, TaskStage

__all__ = [
    "STAGE_PROPOSAL_PHRASES",
    "detect_stage_proposal",
]

# Таблица «этап → фразы», ЕДИНСТВЕННЫЙ источник правды о распознавании.
# Порядок групп — от самых дальних этапов к ближним: при нескольких
# совпадениях выигрывает самый дальний этап прямого хода (модель, сказавшая
# «запускаю тесты и задача выполнена», предлагает завершение, а не валидацию).
STAGE_PROPOSAL_PHRASES: tuple[tuple[TaskStage, tuple[str, ...]], ...] = (
    (
        TaskStage.DONE,
        ("задача завершена", "завершаю задачу", "задача выполнена",
         "можно сдавать", "перехожу к завершению"),
    ),
    (
        TaskStage.VALIDATION,
        ("перехожу к валидации", "приступаю к валидации", "перехожу к проверке",
         "запускаю тесты", "перехожу к тестам"),
    ),
    (
        TaskStage.EXECUTION,
        ("приступаю к реализации", "начинаю реализацию", "перехожу к реализации",
         "начинаю писать код", "приступаю к выполнению", "перехожу к выполнению"),
    ),
    (
        TaskStage.PLANNING,
        ("возвращаюсь к планированию", "перехожу к планированию",
         "начинаю с плана", "составляю план"),
    ),
)

# Шаблоны компилируются один раз на импорт: \b с обеих сторон — совпадение
# должно быть отдельным словом (или фразой), а не началом другого слова
# («запускаю тестирование» предложением не считается).
_STAGE_PROPOSAL_PATTERNS: tuple[tuple[TaskStage, tuple[re.Pattern[str], ...]], ...] = tuple(
    (
        stage,
        tuple(re.compile(r"\b" + re.escape(phrase) + r"\b") for phrase in phrases),
    )
    for stage, phrases in STAGE_PROPOSAL_PHRASES
)


def detect_stage_proposal(text: str) -> Optional[TaskStage]:
    """Этап, о переходе в который говорит текст (``None`` — предложения нет)."""
    lowered = text.lower()
    if not lowered.strip():
        return None

    found = [
        stage
        for stage, patterns in _STAGE_PROPOSAL_PATTERNS
        if any(pattern.search(lowered) for pattern in patterns)
    ]
    if not found:
        return None
    # Самый дальний по прямому ходу: STAGE_ORDER — единственный порядок этапов.
    return max(found, key=STAGE_ORDER.index)
