"""День 17: Streamlit-чат агентов DeepSeek со своим MCP-сервером и вызовом инструментов.

Приложение общается с FastAPI-бэкендом (порт 8000) по HTTP через `requests`.
Ключ DEEPSEEK_API_KEY фронтенду НЕ нужен — его читает бэкенд (day17/.env или
переменная окружения). Все данные хранит бэкенд в SQLite (day17/agents.db),
поэтому они переживают рестарт.

Что нового по сравнению с днём 16: **свой MCP-сервер и вызов инструментов**.
В дне лежит собственный MCP-сервер (`day17/mcp_server/`, транспорт stdio) с тремя
инструментами поверх jsonplaceholder.typicode.com: `get_user`, `get_post`,
`list_user_posts`. Раздел «🔌 MCP» подключается к нему (или к любому другому
серверу: stdio, SSE, Streamable HTTP), показывает каталог `tools/list` с
`input_schema`/`output_schema`, позволяет вызвать инструмент вручную (`tools/call`)
и показывает каталог известных серверов. Главное: в блоке «🤖 Спросить агента»
агент САМ решает по ключевым словам реплики, нужен ли вызов, вызывает инструмент и
использует полученные данные в ответе — вызванный инструмент, аргументы и признак
того, что данные ушли в промпт, видны в ответе.

День 16 добавил MCP-клиент и каталог инструментов; день 15 — контролируемые
переходы состояния задачи; день 14 — инварианты.

День 15 добавил **контролируемые переходы** состояния задачи: задача ходит по
этапам только по объявленному графу, переход вперёд открыт после согласования
этапа, а недопустимая попытка отклоняется с объяснением и попадает в журнал.
День 14 добавил **инварианты** — правила проекта, которые агент не имеет права
нарушать: они подставляются в системный промпт, а предложение проверяется
детерминированными правилами и, при неоднозначности, вызовом LLM.

Интерфейс — пять разделов основной области (переключатель вверху страницы):

- «💬 Чат и память» — диалог вручную, панели трёх слоёв памяти (краткосрочная,
  рабочая, долговременная), индикатор того, что ушло в последний запрос,
  сравнение режимов сжатия; предупреждение или отказ по инвариантам последнего
  хода показывается прямо над полем ввода; стратегия, задача и сессия — в
  боковой панели;
- «👤 Профиль пользователя» — выбор профиля, форма редактирования, готовые
  профили для демонстрации, быстрое переключение профиля активного агента и
  сравнение двух профилей на одном вопросе;
- «🧭 Состояние задачи» — текущий этап и шаг, ожидаемое действие, граф допуска,
  доступные и недоступные переходы с причинами, флаги-согласования и журнал в
  двух разрезах: состоявшиеся переходы и отклонённые попытки;
- «📏 Инварианты» — список правил проекта с фильтрами, форма создания, правка,
  включение-выключение и удаление, а также проверка произвольного текста тем же
  способом, которым агент проверяет свой ход;
- «🔌 MCP» — цель подключения (URL или команда запуска), транспорт, кнопки
  «Подключиться»/«Отключиться», статус соединения, каталог известных серверов,
  таблица инструментов с полными `input_schema`/`output_schema`, кнопка
  обновления списка, форма ручного вызова инструмента с результатом и блок
  «🤖 Спросить агента»: агент сам вызывает инструмент по реплике и отвечает по
  полученным данным.

Запуск из папки day17/:  streamlit run app.py  (бэкенд запускается отдельно:
uvicorn backend.api.main:app --port 8000)

Код интерфейса разложен по пакету ``frontend/``: ``api_client`` (HTTP-транспорт),
``common`` (подписи, форматтеры, состояние), ``sidebar``, ``chat_section``,
``context_panels``, ``memory_panels``, ``profile_section``,
``profile_comparison``, ``task_panel``, ``task_transitions``, ``invariant_panel``,
``mcp_section``, ``mcp_api`` (HTTP-запросы MCP), ``mcp_call`` (ручной вызов
инструмента и каталог серверов), ``mcp_ask`` (агент с шагом MCP).
"""
