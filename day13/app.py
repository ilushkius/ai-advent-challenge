"""День 13: Streamlit-чат агентов DeepSeek с состоянием задачи и памятью.

Приложение общается с FastAPI-бэкендом (порт 8000) по HTTP через `requests`.
Ключ DEEPSEEK_API_KEY фронтенду НЕ нужен — его читает бэкенд (day13/.env или
переменная окружения). Все данные хранит бэкенд в SQLite (day13/agents.db),
поэтому они переживают рестарт.

Что нового по сравнению с днём 12: **состояние задачи как конечный автомат**.
Задача живёт в таблицах `task_states`/`task_transitions`, проходит этапы
planning → execution → validation → done и шаги внутри этапа; состояние
подключается к системному промпту каждого запроса, поэтому после перезапуска
процесса агенту не нужно объяснять, где он остановился. Реплики «пауза»,
«продолжи», «подтверждаю», «вернись на предыдущий этап» обновляют состояние
автоматически.

Интерфейс — три раздела основной области (переключатель вверху страницы):

- «💬 Чат и память» — диалог вручную, панели трёх слоёв памяти (краткосрочная,
  рабочая, долговременная), индикатор того, что ушло в последний запрос,
  сравнение режимов сжатия; стратегия, задача и сессия — в боковой панели;
- «👤 Профиль пользователя» — выбор профиля, форма редактирования, готовые
  профили для демонстрации, быстрое переключение профиля активного агента и
  сравнение двух профилей на одном вопросе;
- «🧭 Состояние задачи» — текущий этап и шаг, ожидаемое действие, схема
  переходов, пять кнопок (пауза, продолжение, следующий шаг, откат, завершение)
  и журнал переходов.

Запуск из папки day13/:  streamlit run app.py  (бэкенд запускается отдельно:
uvicorn backend.main:app --port 8000)

Код интерфейса разложен по пакету ``ui/``: ``api_client`` (HTTP-транспорт),
``common`` (подписи, форматтеры, состояние), ``sidebar``, ``chat_section``,
``context_panels``, ``memory_panels``, ``profile_section``,
``profile_comparison``, ``task_panel``.
"""
