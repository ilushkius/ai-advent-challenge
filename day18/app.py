"""День 18: Streamlit-чат агентов DeepSeek с планировщиком фоновых задач.

Приложение общается с FastAPI-бэкендом (порт 8000) по HTTP через `requests`.
Ключ DEEPSEEK_API_KEY фронтенду НЕ нужен — его читает бэкенд (day18/.env или
переменная окружения). Все данные хранит бэкенд в SQLite (day18/agents.db),
поэтому они переживают рестарт.

Что нового по сравнению с днём 17: **планировщик фоновых задач**. Три инструмента
получают отложенное и периодическое выполнение: `schedule_reminder` (разовое
напоминание), `collect_data` (периодический сбор данных из внешнего API) и
`generate_summary` (регулярная сводка по накопленным данным). Задачи живут в
процессе бэкенда (APScheduler), их метаданные лежат в таблице `scheduled_tasks`,
поэтому задачи переживают перезапуск приложения. Новый раздел «🗓 Планировщик»
показывает задачи, позволяет поставить их вручную (пауза, возобновление, запуск
вне расписания, удаление), показывает напоминания, сводки с метриками и историю
запусков; непрочитанные уведомления планировщика появляются в основной области
чата сами (фрагмент обновляется каждые 5 секунд). Те же инструменты вызывает агент
по реплике — и результат этого виден в отчёте хода строкой «🗓 Планировщик: …».

День 17 добавил MCP-клиент, свой MCP-сервер и вызов инструментов; день 15 —
контролируемые переходы состояния задачи; день 14 — инварианты.

Интерфейс — шесть разделов основной области (переключатель вверху страницы):

- «💬 Чат и память» — диалог вручную, панели трёх слоёв памяти, индикатор того,
  что ушло в последний запрос, сравнение режимов сжатия, уведомления планировщика;
- «👤 Профиль пользователя» — выбор профиля, форма редактирования, готовые
  профили для демонстрации, сравнение двух профилей на одном вопросе;
- «🧭 Состояние задачи» — этап и шаг, ожидаемое действие, граф допуска,
  доступные и недоступные переходы с причинами, флаги-согласования и журнал;
- «📏 Инварианты» — правила проекта с фильтрами, форма создания, правка,
  включение-выключение и удаление, проверка произвольного текста;
- «🔌 MCP» — цель подключения, транспорт, статус, каталог серверов, таблица
  инструментов (шесть у своего сервера), ручной вызов и блок «🤖 Спросить агента»;
- «🗓 Планировщик» — состояние планировщика, таблица задач с действиями, форма
  создания задачи по аргументам инструмента, напоминания, сводки с метриками и
  текстом, история запусков задачи.

Запуск из папки day18/:  streamlit run app.py  (бэкенд запускается отдельно:
uvicorn backend.api.main:app --port 8000)

Код интерфейса разложен по пакету ``frontend/``: ``api_client`` (HTTP-транспорт),
``common`` (подписи, форматтеры, состояние), ``sidebar``, ``chat_section``,
``context_panels``, ``memory_panels``, ``profile_section``,
``profile_comparison``, ``task_panel``, ``task_transitions``, ``invariant_panel``,
``mcp_section``, ``mcp_api`` (HTTP-запросы MCP), ``mcp_call`` (ручной вызов
инструмента), ``mcp_ask`` (агент с шагом MCP), ``scheduler_api`` (HTTP-запросы
планировщика), ``scheduler_section`` (раздел «🗓 Планировщик») и
``notifications`` (уведомления фоновых задач в области чата).
"""
