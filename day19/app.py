"""День 19: Streamlit-чат агентов DeepSeek с пайплайнами MCP-инструментов.

Приложение общается с FastAPI-бэкендом (порт 8000) по HTTP через `requests`.
Ключ DEEPSEEK_API_KEY фронтенду НЕ нужен — его читает бэкенд (day19/.env или
переменная окружения). Все данные хранит бэкенд в SQLite (day19/agents.db),
поэтому они переживают рестарт.

Что нового по сравнению с днём 18: **декларативный пайплайн MCP-инструментов**.
Три инструмента композиции — `search` (найти данные в источнике: лента
jsonplaceholder, файл внутри папки дня или таблица SQLite дня), `summarize`
(сводка списка элементов и ключевые пункты) и `save_to_file` (запись текста в файл
каталога `output/`) — вызываются по очереди одним пайплайном. Пайплайн описан
данными (шаги, аргументы, условия перехода), данные между шагами передаются
маппингом (`$steps.0.structured.items`), а каждый шаг логируется в таблицу
`pipeline_steps` с входными аргументами, результатом и временем выполнения; запуск
и его итог — в `pipeline_runs`. Прогон запускается и из чата: реплика «найди статьи
про RAG, сделай сводку и сохрани в файл» распознаётся агентом, а результат уходит в
системный промпт этого же запроса (в сводке хода — строка «🔀 Пайплайн: …»). Новый
раздел «🔀 Пайплайны» показывает подключение к серверу дня, форму запуска, прогресс
по шагам (обновление раз в секунду), схему потока данных с объёмами и историю
запусков.

День 18 добавил планировщик фоновых задач, день 17 — MCP-клиент, свой сервер и
вызов инструментов, день 15 — контролируемые переходы состояния задачи, день 14 —
инварианты.

Интерфейс — семь разделов основной области (переключатель вверху страницы):

- «💬 Чат и память» — диалог вручную, панели трёх слоёв памяти, индикатор того,
  что ушло в последний запрос, сравнение режимов сжатия, уведомления планировщика;
- «👤 Профиль пользователя» — выбор профиля, форма редактирования, готовые
  профили для демонстрации, сравнение двух профилей на одном вопросе;
- «🧭 Состояние задачи» — этап и шаг, ожидаемое действие, граф допуска,
  доступные и недоступные переходы с причинами, флаги-согласования и журнал;
- «📏 Инварианты» — правила проекта с фильтрами, форма создания, правка,
  включение-выключение и удаление, проверка произвольного текста;
- «🔌 MCP» — цель подключения, транспорт, статус, каталог серверов, таблица
  инструментов (девять у своего сервера), ручной вызов и блок «🤖 Спросить агента»;
- «🗓 Планировщик» — состояние планировщика, таблица задач с действиями, форма
  создания задачи по аргументам инструмента, напоминания, сводки с метриками и
  текстом, история запусков задачи;
- «🔀 Пайплайны» — подключение к серверу дня, запуск пайплайна, прогресс по шагам,
  схема потока данных с объёмами, история запусков с деталями шагов и удалением.

Запуск из папки day19/:  streamlit run app.py  (бэкенд запускается отдельно:
uvicorn backend.api.main:app --port 8000)

Код интерфейса разложен по пакету ``frontend/``: ``api_client`` (HTTP-транспорт),
``common`` (подписи, форматтеры, состояние), ``sidebar``, ``chat_section``,
``context_panels``, ``memory_panels``, ``profile_section``,
``profile_comparison``, ``task_panel``, ``task_transitions``, ``invariant_panel``,
``mcp_section``, ``mcp_api`` (HTTP-запросы MCP), ``mcp_call`` (ручной вызов
инструмента), ``mcp_ask`` (агент с шагом MCP), ``scheduler_api`` (HTTP-запросы
планировщика), ``scheduler_section`` (раздел «🗓 Планировщик»), ``notifications``
(уведомления фоновых задач в области чата), ``pipeline_api`` (HTTP-запросы
пайплайна) и ``pipeline_section`` (раздел «🔀 Пайплайны»).
"""
