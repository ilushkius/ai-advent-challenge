def demo_profile(user_id: str) -> Dict[str, Any]:
    """Данные профиля демонстрации по user_id (``KeyError``, если такого нет)."""
    for item in DEMO_PROFILES:
        if item["user_id"] == user_id:
            return dict(item["profile"])
    raise KeyError(f"профиль демонстрации {user_id!r} не описан")


def demo_titles() -> Dict[str, str]:
    """``user_id → заголовок`` для селекторов интерфейса."""
